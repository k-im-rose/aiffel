"""집중 분석 종목: 사용자가 특히 깊게 보고 싶은 종목을 AI 단계(선별·편집·보고서 분석·대본)에 알리는 공통 도우미.

원칙
- 집중 분석은 '더 많은 뉴스'가 아니라 '투자 이유와 위험 요인에 비춘 더 깊은 분석'을 뜻한다.
- 관련성이 낮은 기사를 집중 종목 때문에 넣거나, 뉴스가 없는 날 내용을 만들지 않는다.
- 집중 종목이 다른 종목·거시·산업의 중요한 뉴스를 빼는 근거가 되지 않는다 (가점일 뿐 절대 조건이 아니다).
- 집중 분석 종목이 하나도 없으면 아래 함수는 빈 값을 돌려주어, 기존 프롬프트와 점수가 그대로 유지된다.
"""
from __future__ import annotations

FOCUS_BONUS = 0.3  # 규칙 점수 가산. 중요도(1~3)·근거 수준보다 훨씬 작아 다른 중요 기사를 밀어내지 못한다.
FOCUS_MARK = "집중 분석"


def names(profile: dict) -> list[str]:
    return [s["name"] for s in profile.get("stocks", []) if s.get("focus") is True and s.get("name")]


def has_focus_text(text: str) -> bool:
    return f"[{FOCUS_MARK}]" in text


def profile_line(profile: dict) -> str:
    """프로필 문장 끝에 붙는 한 줄. 집중 종목이 없으면 빈 문자열."""
    n = names(profile)
    return f"[{FOCUS_MARK}] " + ", ".join(n) if n else ""


